import { describe, expect, it } from "vitest";
import { extractArxivHtml, extractHtml, parseArxivAbsMeta } from "../src/lib/extract";
import { extractPdf, isAllCapsHeading } from "../src/lib/extract-pdf";
import { fixture } from "./helpers";

describe("extractArxivHtml", () => {
  const r = extractArxivHtml(fixture("arxiv-paper.html").toString())!;

  it("keeps title, headings, math alttext and drops page chrome", () => {
    expect(r.title).toBe("Grounded Citation Checking with Small Models");
    expect(r.text).toContain("## 1 Introduction");
    expect(r.text).toContain("## Abstract");
    expect(r.text).toContain("s = \\alpha s_{lex}");
    expect(r.text).not.toContain("Report Issue");
    expect(r.text).not.toContain("Generated by LaTeXML");
    expect(r.text).not.toContain("arxiv page script");
  });

  it("returns null for pages that aren't LaTeXML papers", () => {
    expect(extractArxivHtml(fixture("arxiv-html-stub.html").toString())).toBeNull();
  });
});

describe("extractHtml", () => {
  it("extracts the article body without nav/footer", () => {
    const r = extractHtml(fixture("blog-article.html").toString(), "https://blog.test/post");
    expect(r.text).toContain("Every academic field depends on citations");
    expect(r.text).toContain("## What a checker should do");
    expect(r.text).not.toContain("Archive");
    expect(r.text).not.toContain("All rights reserved");
  });

  it("falls back to <main> when Readability keeps under half of it", () => {
    // Many short link-heavy blocks: Readability discards most of it.
    const items = Array.from({ length: 40 }, (_, i) => `<div><a href="/p${i}">Paper ${i} on topic ${i}</a></div>`).join("");
    const html = `<html><head><title>Index</title></head><body><main>${items}</main></body></html>`;
    const r = extractHtml(html, "https://index.test/");
    expect(r.text).toContain("Paper 0 on topic 0");
    expect(r.text).toContain("Paper 39 on topic 39");
  });
});

describe("parseArxivAbsMeta", () => {
  it("reads citation_* meta tags", () => {
    expect(parseArxivAbsMeta(fixture("arxiv-abs.html").toString())).toEqual({
      title: "Grounded Citation Checking with Small Models",
      authors: "Example, Ada; Sample, Bo",
    });
  });
});

describe("extractPdf", () => {
  it("rebuilds paragraphs, detects all-caps headings, rejoins hyphenation", async () => {
    const r = await extractPdf(new Uint8Array(fixture("sample.pdf")));
    expect(r.title).toBe("Tiny Fixture Paper on Citation Checking");
    expect(r.text).toContain("## ABSTRACT");
    expect(r.text).toContain("## 1 INTRODUCTION");
    expect(r.text).toContain("## 2 RESULTS");
    expect(r.text).toContain("hyphenated words like transformer should be rejoined");
    expect(r.text).toContain(
      "Citations generated by language models are often plausible but unsupported. Checking each one by hand",
    );
    // The two intro paragraphs stay separate.
    expect(r.text).toMatch(/retrievable chunks\.\n\nThe second paragraph/);
  });
});

describe("isAllCapsHeading", () => {
  it.each(["ABSTRACT", "1 INTRODUCTION", "2.3 RELATED WORK", "REFERENCES"])("accepts %s", (line) => {
    expect(isAllCapsHeading(line)).toBe(true);
  });
  it.each(["HUTP-97/A097", "N − M + MU4", "Introduction", "WE PROPOSE A METHOD.", "GPT-4"])("rejects %s", (line) => {
    expect(isAllCapsHeading(line)).toBe(false);
  });
});
